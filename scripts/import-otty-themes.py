"""Import complete Otty theme configuration, retaining author and source hashes.

Only configuration values are emitted; source comments and descriptions are not
copied. No Otty implementation, binary or font is distributed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "assets/themes/otty"
RETAINED_SOURCES = ("solarized-light.ottytheme",)


def yaml(data, indent=0):
    lines = []
    for key, value in data.items():
        prefix = " " * indent + key + ":"
        if isinstance(value, dict) and value:
            lines.append(prefix)
            lines.extend(yaml(value, indent + 2))
        else:
            lines.append(prefix + " " + json.dumps(value, ensure_ascii=False))
    return lines


def convert(path):
    raw = path.read_bytes()
    source = tomllib.loads(raw.decode("utf-8-sig"))
    style = json.loads(json.dumps(source))
    style["meta"].pop("description", None)
    terminal = source["terminal"]
    palette = terminal["palette"]
    assert len(palette) == 16, path
    for color in palette:
        assert len(color) == 7 and color.startswith("#"), (path, color)
        int(color[1:], 16)
    background = terminal["background"]
    if background == "none":
        background = source.get("panel", {}).get(
            "surface", "#1E1E1E" if source["meta"]["mode"] == "dark" else "#FFFFFF")
    theme = {
        "name": source["meta"]["name"],
        "background": background,
        "foreground": terminal["foreground"],
        "accent": source.get("token", {}).get("accent", palette[4]),
        "cursor": terminal.get("cursor", source.get("cursor", {}).get("color", terminal["foreground"])),
    }
    if selection := terminal.get("selection-background"):
        theme["selection"] = selection
    theme["ansi"] = {"normal": palette[:8], "bright": palette[8:]}
    theme["style"] = style
    content = (
        "# Generated by scripts/import-otty-themes.py; complete declarative profile.\n"
        f"# Source: {path.name}; SHA-256: {hashlib.sha256(raw).hexdigest()}\n"
        "# Original author and platform overrides are retained below.\n"
        + "\n".join(yaml(theme)) + "\n"
    )
    return content, {
        "id": "otty-" + path.stem,
        "name": theme["name"],
        "author": source["meta"].get("author"),
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "yaml_sha256": hashlib.sha256(content.encode()).hexdigest(),
        "mode": source["meta"]["mode"],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path)
    parser.add_argument("--output", type=Path, default=DESTINATION)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest_path = args.output / "manifest.json"
    if args.check and args.source_dir is None:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        assert [theme["id"] for theme in manifest["themes"]] == ["otty-solarized-light"]
        assert manifest["themes"][0]["name"] == "Solarized Light"
        expected = set()
        for theme in manifest["themes"]:
            path = args.output / (theme["id"] + ".yaml")
            assert hashlib.sha256(path.read_bytes()).hexdigest() == theme["yaml_sha256"], path
            expected.add(path.name)
        assert expected == {p.name for p in args.output.glob("*.yaml")}
        print(f"Verified {len(expected)} complete packaged theme profiles.")
        return
    source_dir = args.source_dir or Path.home() / ".config/otty/themes"
    files = [source_dir / name for name in RETAINED_SOURCES]
    assert all(path.is_file() for path in files), f"Missing retained source in {source_dir}"
    args.output.mkdir(parents=True, exist_ok=True)
    entries = []
    for path in files:
        content, entry = convert(path)
        target = args.output / (entry["id"] + ".yaml")
        if args.check:
            assert target.read_text(encoding="utf-8") == content, target
        else:
            target.write_text(content, encoding="utf-8", newline="\n")
        entries.append(entry)
    manifest = {
        "source": "Otty 1.6.0-beta theme configuration",
        "reference": "https://docs.otty.sh/reference/theme-format",
        "themes": entries,
    }
    content = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    if args.check:
        assert manifest_path.read_text(encoding="utf-8") == content
    else:
        manifest_path.write_text(content, encoding="utf-8", newline="\n")
    assert {entry["id"] + ".yaml" for entry in entries} == {
        path.name for path in args.output.glob("*.yaml")
    }, "Output contains unretained theme profiles"
    print(f"{'Verified' if args.check else 'Imported'} {len(entries)} complete Otty profiles.")


if __name__ == "__main__":
    main()
